// Builds the Windows installers, one per edition (editions.json):
//   dist/Stagio-Lite-Setup-<version>.exe, dist/Stagio-Standard-Setup-…, dist/Stagio-Extra-Setup-…
//   1. electron-builder packs the app once into dist/win-unpacked (no installer step)
//   2. makensis compiles build/installer.nsi around that folder for each edition; the installer
//      writes resources/edition.json, which tells the app which edition it is (lib/edition.js)
//
// The installer is our own NSIS script because electron-builder's NSIS target runs a
// freshly compiled program at build time to make the uninstaller, and some antivirus software
// removes that file. Nothing here runs a generated program.
//
//   node build/make-installer.js                     pack + all three installers
//   node build/make-installer.js --edition=extra     pack + that one (repeat for more)
//   node build/make-installer.js --no-pack           installers from the existing dist/win-unpacked
//   node build/make-installer.js --pack-only         only step 1 (CI signs Stagio.exe in between)
//
// makensis: STAGIO_MAKENSIS, else the copy electron-builder keeps in its cache
// (%LOCALAPPDATA%\electron-builder\Cache\nsis-*), else makensis on PATH.
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SRC = path.join(DIST, 'win-unpacked');
const EDITIONS = JSON.parse(fs.readFileSync(path.join(ROOT, 'editions.json'), 'utf8'));
const { versionLabel } = require('../lib/edition');
// Each edition's "Apps" entry. Never change these: Windows knows an installed edition by them.
// Standard keeps the ID OneDesk 0.x had (Stagio's earlier name), so it installs over it as an update.
const GUIDS = {
  lite: '515c6c2a-09b3-4629-8053-21afa5a6045c',
  standard: 'bf75d2b2-2ca8-5a43-b2e2-970b8867500c',
  extra: '19d6387d-1e8a-467c-b972-5902281c96c8',
};
const APP_IDS = { lite: 'app.onedesk.lite', standard: 'app.onedesk.console', extra: 'app.onedesk.extra' };
const wanted = process.argv.filter((a) => a.startsWith('--edition=')).map((a) => a.slice(10));
const editions = wanted.length ? wanted : Object.keys(EDITIONS);
for (const e of editions) if (!EDITIONS[e] || !GUIDS[e]) { console.error(`Unknown edition: ${e}`); process.exit(1); }

function fail(msg) { console.error(`\n${msg}`); process.exit(1); }
function sleep(ms) { Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms); }

function cacheDirs(prefix) {
  const cache = process.env.ELECTRON_BUILDER_CACHE ||
    path.join(process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local'), 'electron-builder', 'Cache');
  const out = [];
  let tops = [];
  try { tops = fs.readdirSync(cache).filter((d) => d.startsWith(prefix)).sort().reverse(); } catch { return out; }
  for (const top of tops) {
    let subs = [];
    try { subs = fs.readdirSync(path.join(cache, top)); } catch { continue; }
    for (const sub of subs) out.push(path.join(cache, top, sub));
  }
  return out;
}

function findMakensis() {
  if (process.env.STAGIO_MAKENSIS) return process.env.STAGIO_MAKENSIS;
  for (const dir of cacheDirs('nsis-')) {
    if (path.basename(path.dirname(dir)).startsWith('nsis-resources')) continue;
    for (const exe of [path.join(dir, 'makensis.exe'), path.join(dir, 'Bin', 'makensis.exe')]) {
      if (fs.existsSync(exe) && fs.existsSync(path.join(dir, 'Include', 'MUI2.nsh'))) return exe;
    }
  }
  const which = spawnSync('where', ['makensis'], { encoding: 'utf8' });
  if (which.status === 0) return which.stdout.split(/\r?\n/)[0].trim();
  return null;
}

function findPluginDir() {
  for (const dir of cacheDirs('nsis-resources')) {
    const p = path.join(dir, 'plugins', 'x86-unicode');
    if (fs.existsSync(path.join(p, 'WinShell.dll'))) return p;
  }
  return null;
}

// What the uninstaller removes: exactly the top-level entries of win-unpacked.
function writeFileList(file) {
  const lines = ['; generated by build/make-installer.js'];
  for (const e of fs.readdirSync(SRC, { withFileTypes: true })) {
    const p = `$INSTDIR\\${e.name}`;
    lines.push(e.isDirectory() ? `RMDir /r "${p}"` : `Delete "${p}"`);
  }
  fs.writeFileSync(file, lines.join('\r\n') + '\r\n');
}

// ---- 1. pack ----------------------------------------------------------------
const started = Date.now();
if (!process.argv.includes('--no-pack')) {
  console.log('Packing Stagio (electron-builder --win dir) ...');
  const cli = path.join(ROOT, 'node_modules', 'electron-builder', 'cli.js');
  const r = spawnSync(process.execPath, [cli, '--win', 'dir', '--x64', '--publish', 'never'], { cwd: ROOT, stdio: 'inherit' });
  if (r.status !== 0) fail('electron-builder failed (see above).');
}
const asar = path.join(SRC, 'resources', 'app.asar');
if (!fs.existsSync(path.join(SRC, 'Stagio.exe')) || !fs.existsSync(asar)) fail(`No packed app in ${SRC}.`);
if (!process.argv.includes('--no-pack') && fs.statSync(asar).mtimeMs < started - 5000) fail('dist/win-unpacked was not updated.');
if (process.argv.includes('--pack-only')) { console.log(`Packed: ${SRC}`); process.exit(0); }

// ---- 2. installer -----------------------------------------------------------
const makensis = findMakensis();
if (!makensis) {
  fail('makensis not found. Either run "npx electron-builder --win nsis" once (it downloads NSIS into its cache),\n' +
    'install NSIS 3 from https://nsis.sourceforge.io, or set STAGIO_MAKENSIS to makensis.exe.');
}
const pluginDir = findPluginDir();
const fileList = path.join(DIST, 'installer-files.nsh');
writeFileList(fileList);
if (!pluginDir) console.log('(WinShell plugin not found: shortcuts get no app ID; everything else is the same.)');
const side = path.join(__dirname, 'installer-side.bmp'); // made by build/make-installer-art.ps1

for (const id of editions) {
  const ed = EDITIONS[id];
  const VERSION = ed.windows;
  const OUT = path.join(DIST, `${ed.name.replace(/ /g, '-')}-Setup-${VERSION}.exe`);
  try { fs.unlinkSync(OUT); } catch { /* not there */ }
  const numver = (VERSION.split(/[-+]/)[0].split('.').map((n) => parseInt(n, 10) || 0).concat([0, 0, 0, 0])).slice(0, 4).join('.');
  const defs = {
    VERSION, NUMVER: numver, VLABEL: versionLabel(VERSION), EDITION: id, EDNAME: ed.name,
    OLDNAME: ed.name.replace(/^Stagio/, 'OneDesk'), // Stagio was called OneDesk until 2026-11: its shortcuts are renamed
    GUID: GUIDS[id], APPID: APP_IDS[id],
    SRC, OUTFILE: OUT, FILELIST: fileList, ICON: path.join(__dirname, 'icon.ico'),
  };
  if (pluginDir) defs.PLUGINDIR = pluginDir;
  if (fs.existsSync(side)) defs.SIDEBMP = side;
  const args = ['/V2', '/INPUTCHARSET', 'UTF8', ...Object.entries(defs).map(([k, v]) => `/D${k}=${v}`), path.join(__dirname, 'installer.nsi')];

  console.log(`
Compiling the ${ed.name} ${defs.VLABEL} installer with ${makensis}`);
  const t0 = Date.now();
  const r = spawnSync(makensis, args, { cwd: __dirname, stdio: 'inherit' });
  if (r.status !== 0) {
    try { fs.unlinkSync(OUT); } catch { /* nothing written */ } // never leave a half-written installer behind
    fail(`makensis failed for ${ed.name} (exit code ${r.status}${r.signal ? `, ${r.signal}` : ''}; see above). No installer was made.`);
  }

  // Security software sometimes removes a new unsigned exe a few seconds after it appears.
  sleep(5000);
  if (!fs.existsSync(OUT)) fail(`${OUT} is gone right after the build. Check the antivirus quarantine.`);
  const size = fs.statSync(OUT).size;
  if (size < 50 * 1024 * 1024) fail(`${OUT} is only ${(size / 1048576).toFixed(1)} MB; something went wrong.`);
  const sha = crypto.createHash('sha256').update(fs.readFileSync(OUT)).digest('hex');
  console.log(`Done in ${Math.round((Date.now() - t0) / 1000)} s: ${OUT}`);
  console.log(`  ${(size / 1048576).toFixed(1)} MB  sha256 ${sha}`);
}
